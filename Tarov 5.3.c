#include <stdio.h>

int main(void)
{
    /*
    int Nзкс = 111260309;
    int K = 0;
    int Вариант = ((Nзкс + (K + 12)) % 30) + 1;   // = 12
    */

    int N;
    printf("Enter N (<=0 to exit): ");
    
    while (scanf("%d", &N) == 1 && N > 0)
    {
        double S = 0.0; 
        int i;

        for (i = 1; i <= N; i++)
        {
            S += (double)(i * i * i); 
        }

        printf("SUM: %.6f\n", S);
        printf("Enter N (<=0 to exit): ");
    }

    return 0;
}

/* Аккумулятор S типа double инициализируется 0.0, а не 0, потому что
   при накоплении вещественного ряда результат может стать очень большим
   или очень маленьким. Если использовать int, дробная часть будет
   отбрасываться при каждом сложении (хотя в данном варианте f(i) целые,
   тип double обязателен по заданию для единообразия и предотвращения
   переполнения int при больших N). */
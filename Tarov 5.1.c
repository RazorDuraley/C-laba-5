#include <stdio.h>
#include <math.h>

#define PI 3.14159265358979323846

int main(void)
{
    /*
    int Nзкс = 111260309;
    int K = 0;
    int Вариант = (Nзкс % 30) + 1;   // = 30
    */

    double A = 0.0;
    double B = 3.1415926535;
    double H = 0.5;
    double X, Y;
    int i = 0;

    printf("Iter |    X    |    Y    \n");
    printf("-------------------------\n");

    for (i = 0; A + i * H <= B + 1e-9; i++)
    {
        X = A + i * H;
        Y = cos(2.0 * X) + 1.0;   

        printf("%4d | %7.4f | %7.4f\n", i + 1, X, Y);
    }

    return 0;
}

/* При использовании вещественного счетчика (for (double x = A; x <= B; x += H))
   из-за ограниченной точности double (двоичное представление) при каждом
   прибавлении H накапливается ошибка. В итоге x может стать чуть больше B
   (например, PI + 0.0000000001), и условие x <= B сработает неверно —
   конечная точка будет пропущена. Поэтому надежнее считать X = A + i * H
   по целому счетчику. */